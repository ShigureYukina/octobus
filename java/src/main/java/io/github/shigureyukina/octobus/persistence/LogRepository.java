package io.github.shigureyukina.octobus.persistence;

import com.fasterxml.jackson.core.type.TypeReference;
import com.fasterxml.jackson.databind.ObjectMapper;
import io.github.shigureyukina.octobus.domain.ChannelAttempt;
import io.github.shigureyukina.octobus.domain.LogFilter;
import io.github.shigureyukina.octobus.domain.RelayLog;
import java.util.ArrayList;
import java.util.List;
import org.springframework.jdbc.core.BatchPreparedStatementSetter;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.stereotype.Repository;

/**
 * Repository for the relay_log table with read filtering/pagination and write support.
 */
@Repository
public class LogRepository {

    private static final TypeReference<List<ChannelAttempt>> ATTEMPTS_TYPE = new TypeReference<>() {};

    private final JdbcTemplate jdbcTemplate;
    private final ObjectMapper objectMapper;

    public LogRepository(JdbcTemplate jdbcTemplate, ObjectMapper objectMapper) {
        this.jdbcTemplate = jdbcTemplate;
        this.objectMapper = objectMapper;
    }

    // ========== Reads ==========

    /**
     * Returns a paginated list of relay logs matching the given filter.
     */
    public List<RelayLog> findAll(LogFilter filter) {
        var sql = new StringBuilder(
            "SELECT id, time, request_model_name, request_api_key_name, channel_id, channel_name, "
            + "actual_model_name, input_tokens, output_tokens, ftut, use_time, cost, "
            + "usage_recorded, request_content, response_content, error, attempts, "
            + "total_attempts, cache_hit_tokens "
            + "FROM relay_log WHERE 1=1"
        );
        var params = new ArrayList<Object>();

        applyCommonFilters(sql, params, filter);

        sql.append(" ORDER BY time DESC LIMIT ? OFFSET ?");
        params.add(filter.pageSize());
        params.add(filter.offset());

        return jdbcTemplate.query(sql.toString(), (rs, rowNum) -> mapRelayLog(rs), params.toArray());
    }

    /**
     * Returns the total count of relay logs matching the given filter.
     */
    public long count(LogFilter filter) {
        var sql = new StringBuilder("SELECT COUNT(*) FROM relay_log WHERE 1=1");
        var params = new ArrayList<Object>();

        applyCommonFilters(sql, params, filter);

        var result = jdbcTemplate.queryForObject(sql.toString(), Long.class, params.toArray());
        return result != null ? result : 0L;
    }

    // ========== Write ==========

    /**
     * Inserts a new relay log row. The id is auto-generated by the database.
     */
    public void save(RelayLog log) {
        String attemptsJson = serializeAttempts(log.attempts());
        jdbcTemplate.update("""
            INSERT INTO relay_log (time, request_model_name, request_api_key_name,
                channel_id, channel_name, actual_model_name, input_tokens, output_tokens,
                ftut, use_time, cost, usage_recorded, request_content, response_content,
                error, attempts, total_attempts, cache_hit_tokens)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """,
            log.time(),
            log.requestModelName(),
            log.requestApiKeyName(),
            log.channelId(),
            log.channelName(),
            log.actualModelName(),
            log.inputTokens(),
            log.outputTokens(),
            log.ftut(),
            log.useTime(),
            log.cost(),
            log.usageRecorded() ? 1 : 0,
            log.requestContent(),
            log.responseContent(),
            log.error(),
            attemptsJson,
            log.totalAttempts(),
            log.cacheHitTokens()
        );
    }

    /**
     * Inserts multiple relay log rows in a single batch.
     */
    public void saveAll(List<RelayLog> logs) {
        if (logs == null || logs.isEmpty()) {
            return;
        }
        jdbcTemplate.batchUpdate("""
            INSERT INTO relay_log (time, request_model_name, request_api_key_name,
                channel_id, channel_name, actual_model_name, input_tokens, output_tokens,
                ftut, use_time, cost, usage_recorded, request_content, response_content,
                error, attempts, total_attempts, cache_hit_tokens)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
            """, new BatchPreparedStatementSetter() {
            @Override
            public void setValues(java.sql.PreparedStatement ps, int i) throws java.sql.SQLException {
                RelayLog log = logs.get(i);
                ps.setLong(1, log.time());
                ps.setString(2, log.requestModelName());
                ps.setString(3, log.requestApiKeyName());
                ps.setInt(4, log.channelId());
                ps.setString(5, log.channelName());
                ps.setString(6, log.actualModelName());
                ps.setInt(7, log.inputTokens());
                ps.setInt(8, log.outputTokens());
                ps.setInt(9, log.ftut());
                ps.setInt(10, log.useTime());
                ps.setDouble(11, log.cost());
                ps.setInt(12, log.usageRecorded() ? 1 : 0);
                ps.setString(13, log.requestContent());
                ps.setString(14, log.responseContent());
                ps.setString(15, log.error());
                ps.setString(16, serializeAttempts(log.attempts()));
                ps.setInt(17, log.totalAttempts());
                ps.setInt(18, log.cacheHitTokens());
            }

            @Override
            public int getBatchSize() {
                return logs.size();
            }
        });
    }

    /**
     * Returns ALL relay logs without pagination, for backup export.
     */
    public List<RelayLog> findAllForExport() {
        return jdbcTemplate.query(
            "SELECT id, time, request_model_name, request_api_key_name, channel_id, channel_name, "
            + "actual_model_name, input_tokens, output_tokens, ftut, use_time, cost, "
            + "usage_recorded, request_content, response_content, error, attempts, "
            + "total_attempts, cache_hit_tokens "
            + "FROM relay_log ORDER BY id",
            (rs, rowNum) -> mapRelayLog(rs)
        );
    }

    // ========== Delete ==========

    /**
     * Deletes all relay log rows.
     */
    public void deleteAll() {
        jdbcTemplate.update("DELETE FROM relay_log");
    }

    private void applyCommonFilters(StringBuilder sql, ArrayList<Object> params, LogFilter filter) {
        if (filter.startTime() != null) {
            sql.append(" AND time >= ?");
            params.add(filter.startTime());
        }
        if (filter.endTime() != null) {
            sql.append(" AND time <= ?");
            params.add(filter.endTime());
        }
        if (filter.modelName() != null && !filter.modelName().isBlank()) {
            sql.append(" AND request_model_name = ?");
            params.add(filter.modelName());
        }
        if (filter.channelName() != null && !filter.channelName().isBlank()) {
            sql.append(" AND channel_name = ?");
            params.add(filter.channelName());
        }
        if ("error".equals(filter.status())) {
            sql.append(" AND error != ''");
        } else if ("success".equals(filter.status())) {
            sql.append(" AND error = ''");
        }
    }

    private RelayLog mapRelayLog(java.sql.ResultSet rs) throws java.sql.SQLException {
        return new RelayLog(
            rs.getLong("id"),
            rs.getLong("time"),
            rs.getString("request_model_name"),
            rs.getString("request_api_key_name"),
            rs.getInt("channel_id"),
            rs.getString("channel_name"),
            rs.getString("actual_model_name"),
            rs.getInt("input_tokens"),
            rs.getInt("output_tokens"),
            rs.getInt("ftut"),
            rs.getInt("use_time"),
            rs.getDouble("cost"),
            rs.getInt("usage_recorded") != 0,
            rs.getString("request_content"),
            rs.getString("response_content"),
            rs.getString("error"),
            parseAttempts(rs.getString("attempts")),
            rs.getInt("total_attempts"),
            rs.getInt("cache_hit_tokens")
        );
    }

    private List<ChannelAttempt> parseAttempts(String json) {
        if (json == null || json.isBlank()) {
            return List.of();
        }
        try {
            return objectMapper.readValue(json, ATTEMPTS_TYPE);
        } catch (Exception e) {
            return List.of();
        }
    }

    private String serializeAttempts(List<ChannelAttempt> attempts) {
        if (attempts == null || attempts.isEmpty()) {
            return "[]";
        }
        try {
            return objectMapper.writeValueAsString(attempts);
        } catch (Exception e) {
            return "[]";
        }
    }
}
